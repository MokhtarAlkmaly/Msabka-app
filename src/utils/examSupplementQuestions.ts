const ref = (surah: number, ayah: number) => `سورة ${surahName(surah)} — الآية ${ayah}`;

/** أسئلة تطبيقية من النص العثماني نفسه: نون/ميم مشددة وقلقلة عند الوصل.
 * لا نستنتج أحكامًا من نص منزوع التشكيل، ولا نولّد تفسيرًا آليًا.
 */
export function buildSupplementPool(data: QuranData, range: JuzRange): SupplementQuestion[] {
  const first = juzFirstId(data, range.fromJuz);
  const last = juzLastId(data, range.toJuz);
  const pool: SupplementQuestion[] = MEANING_BANK.filter(([s, a]) => {
    const id = toGlobalId(s, a);
    return id >= first && id <= last;
  }).map(([surah, ayah, phrase, answer]) => ({
    kind: "meaning",
    surah,
    ayah,
    reference: ref(surah, ayah),
    question: `ما معنى ﴿${phrase}﴾ في قوله تعالى ﴿${ayahText(data, toGlobalId(surah, ayah))}﴾؟`,
    answer,
  }));
  for (let id = first; id <= last; id++) {
    const text = ayahText(data, id);
    const { surah, ayah } = fromGlobalId(id);
    const word = text.split(/\s+/).find((w) => /[نم][\u064b-\u0650\u0652\u0670]*\u0651/.test(w));
    if (word)
      pool.push({
        kind: "tajweed",
        surah,
        ayah,
        reference: ref(surah, ayah),
        question: `بيّن حكم النون أو الميم المشددة في ﴿${word}﴾، واذكر مقدار الغنة ثم طبّقها عند قراءة الآية.`,
        answer: "تجب الغنة في النون والميم المشددتين بمقدار حركتين، مع التطبيق الصحيح عند التلاوة.",
      });
    const qalqalah = text.split(/\s+/).find((w) => /[قطبجد][ْۡ]/.test(w));
    if (qalqalah)
      pool.push({
        kind: "tajweed",
        surah,
        ayah,
        reference: ref(surah, ayah),
        question: `استخرج حرف القلقلة الساكن من ﴿${qalqalah}﴾ وبيّن حكمه عند الوصل ثم طبّقه.`,
        answer:
          "حرف ساكن من حروف «قطب جد»؛ حكمه القلقلة الصغرى عند الوصل. يُنطق باضطراب الصوت دون إضافة حركة كاملة.",
      });
  }
  return pool;
}

export function pickSupplements(pool: SupplementQuestion[], model: number): SupplementQuestion[] {
  return (["tajweed", "meaning"] as const).flatMap((kind) => {
    const questions = pool.filter((q) => q.kind === kind);
    if (!questions.length) return [];
    return Array.from(
      { length: Math.min(2, questions.length) },
      (_, i) => questions[(model * 2 + i) % questions.length],
    );
  });
}
